const { app } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const root = path.resolve(__dirname, '..')
app.disableHardwareAcceleration()
app.setPath('userData', path.join(root, 'artifacts', 'installed-xml-verification-profile'))
setTimeout(() => app.exit(1), 30_000).unref()
async function main() {
  await app.whenReady()
  const archive = path.join('D:\\app\\LabDeck', 'resources', 'app.asar')
  const { XMLParser } = await import(pathToFileURL(path.join(archive, 'node_modules', 'fast-xml-parser', 'src', 'fxp.js')).href)
  const parser = new XMLParser({ parseTagValue: false })
  const xml = await fs.readFile(path.join(root, 'artifacts', 'nvidia-xml-validation', 'rtx-3080-v12.xml'), 'utf8')
  const parsed = parser.parse(xml)
  if (!parsed.nvidia_smi_log?.gpu) throw new Error('Packaged XML parser did not return GPU data')
  const pkg = JSON.parse(await fs.readFile(path.join(archive, 'package.json'), 'utf8'))
  console.log(JSON.stringify({ installedVersion: pkg.version, packagedXmlRuntimeVerified: true }))
  app.quit()
}
main().catch(error => { console.error(error); app.exit(1) })
